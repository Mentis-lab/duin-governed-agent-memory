#!/usr/bin/env node
// gen-third-party-notices.mjs — aggregate the license texts of every production
// dependency that ships in the installer into THIRD-PARTY-NOTICES.txt.
//
// Two dependency trees ride into the packaged app (see electron-builder.yml):
//   1. the root tree — package.json `dependencies`, unpacked into
//      app.asar.unpacked/node_modules;
//   2. the dsh executor runtime — resources/executors/dsh, whose node_modules is
//      staged by scripts/stage-dsh-runtime.mjs before every build:* (never
//      committed). When it is not staged the section says so instead of being
//      silently empty.
//
// The scan itself is license-checker-rseidelsohn (pinned) run through npx, so
// this script adds no dependency to package.json. `--plainVertical` is the
// Angular-CLI 3rdpartylicenses.txt layout: "name version / license / text".
// `--excludePrivatePackages` drops DUIN's own private packages (duin-dsh-runtime,
// duin-gate) and `--excludePackages` the root package itself — their terms are
// LICENSE + NOTICE, not third-party.
//
// The hand-written parts of the notice (LGPL libvips, dual-license elections,
// bundled models, concept credits) live in NOTICE and licenses/, which ship next
// to this file. Run:
//
//   node scripts/gen-third-party-notices.mjs          # writes THIRD-PARTY-NOTICES.txt
//
// build:* runs it after stage-dsh-runtime.mjs and before electron-builder so the
// shipped file reflects the dependency set of that build.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(REPO, 'THIRD-PARTY-NOTICES.txt')
const CHECKER = 'license-checker-rseidelsohn@4.4.2'
const DSH_DIR = join(REPO, 'resources', 'executors', 'dsh')

const TREES = [
  { label: 'DUIN application (root package.json dependencies)', dir: REPO, staged: true },
  {
    label: 'dsh executor runtime (resources/executors/dsh, staged by scripts/stage-dsh-runtime.mjs)',
    dir: DSH_DIR,
    staged: existsSync(join(DSH_DIR, 'node_modules'))
  }
]

function scan(dir) {
  const self = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const tmp = mkdtempSync(join(tmpdir(), 'duin-tpn-'))
  const out = join(tmp, 'notices.txt')
  try {
    const args = [
      '-y',
      CHECKER,
      '--production',
      '--plainVertical',
      '--excludePrivatePackages',
      '--excludePackages',
      `${self.name}@${self.version}`,
      '--start',
      dir,
      '--out',
      out
    ]
    // npx is npx.cmd on Windows; a .cmd needs a shell to spawn. Every argument is a
    // repo-relative constant, nothing here comes from user input.
    execFileSync(process.platform === 'win32' ? 'npx.cmd' : 'npx', args, {
      cwd: dir,
      stdio: ['ignore', 'ignore', 'inherit'],
      shell: process.platform === 'win32'
    })
    return readFileSync(out, 'utf8').replace(/\r\n/g, '\n').trim()
  } finally {
    rmSync(tmp, { recursive: true, force: true })
  }
}

const rule = '='.repeat(79)
const sections = []
for (const tree of TREES) {
  if (!tree.staged) {
    sections.push(
      `${rule}\n${tree.label}\n${rule}\n\n` +
        'NOT STAGED at generation time: this build carries no dsh runtime, so no packages\n' +
        'are listed for it. A release build stages the runtime first and regenerates this\n' +
        'file; its packages (@deepseek-ai/dsh-* MIT (c) 2026 DeepSeek, node-addon-landlock-run\n' +
        'BSD-3-Clause, koffi MIT, node-pty MIT, and their dependencies) are summarised in NOTICE.\n'
    )
    continue
  }
  const text = scan(tree.dir)
  sections.push(`${rule}\n${tree.label}\n${rule}\n\n${text}\n`)
}

const header =
  'THIRD-PARTY NOTICES FOR DUIN\n' +
  '\n' +
  'DUIN is licensed under the MIT License (LICENSE). This file lists the open-source\n' +
  'packages that ship inside the DUIN installer, with their license texts as found in\n' +
  'each package. It is generated by scripts/gen-third-party-notices.mjs from the\n' +
  'dependency trees of the build; do not edit by hand.\n' +
  '\n' +
  'Also see: NOTICE (attribution, bundled models, dual-license elections, concept\n' +
  'credits) and licenses/ (LGPL-3.0 and GPL-3.0 texts and the sharp/libvips library\n' +
  'table for the dynamically linked libvips that sharp bundles).\n' +
  '\n'

writeFileSync(OUT, header + sections.join('\n') + '\n', 'utf8')
console.log(`[third-party-notices] wrote ${OUT}`)
for (const s of sections) console.log('  ' + s.split('\n')[1])
